"""Module providing a function printing python version."""

class Calculator:
    """Module providing a function printing python version."""
    def __init__(self, op1: float, op2: float):
        self.op1 = op1
        self.op2 = op2

    def sum(self):
        """Module providing a function printing python version."""
        return self.op1 + self.op2

    def subtract(self):
        """Module providing a function printing python version."""
        return self.op1 - self.op2
